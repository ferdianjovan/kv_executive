#!/usr/bin/env python3
"""Exercise generic ROS Python executors without accessing a vehicle graph.

Source the ROS workspace, then run this file with the configured interpreter::

    python scripts/diagnose_ros_executor.py --duration 180 --domain 150

Two child processes run this same file as plain rclpy workers. The parent sends
100 Hz odometry, 50 Hz simulated clock and TF, and 1 Hz Boolean state. It checks
standard parameter services every 15 seconds. Every ROS name, including clock,
rosout and parameter events, is placed below a unique domain/PID namespace.

This diagnostic imports no kv_executive code or generated package interfaces.
It sends no action goals or vehicle commands. It respects the selected
RMW_IMPLEMENTATION so the same workload can compare middleware backends.

JSON event logs, child output and a final summary are written to --output-dir
or a new temporary directory. Fatal parent tracebacks go to parent_fault.log.
If the parent crashes, each worker still exits at its own wall-clock deadline.
The private --worker mode is used only by the parent process.
"""

import argparse
import faulthandler
import json
import math
import os
from pathlib import Path
import re
import secrets
import signal
import subprocess
import sys
import tempfile
import threading
import time
import traceback

from geometry_msgs.msg import TransformStamped

from nav_msgs.msg import Odometry

from rcl_interfaces.msg import ParameterType
from rcl_interfaces.srv import GetParameters

import rclpy
from rclpy.executors import ExternalShutdownException, MultiThreadedExecutor
from rclpy.node import Node
from rclpy.qos import DurabilityPolicy, qos_profile_sensor_data, QoSProfile

from rosgraph_msgs.msg import Clock

from std_msgs.msg import Bool

from tf2_msgs.msg import TFMessage


def arguments():
    """Parse bounded diagnostic options and validate private worker names."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--duration', type=float, default=180.0,
                        help='Wall-clock test duration in seconds (default: 180).')
    parser.add_argument('--domain', type=int, default=100 + secrets.randbelow(81),
                        help='ROS domain ID (default: random value between 100 and 180).')
    parser.add_argument('--output-dir', type=Path,
                        help='New or empty directory for diagnostic artifacts.')
    parser.add_argument('--worker', action='store_true', help=argparse.SUPPRESS)
    parser.add_argument('--namespace', help=argparse.SUPPRESS)
    options = parser.parse_args()
    if not math.isfinite(options.duration) or not 1.0 <= options.duration <= 3615.0:
        parser.error('--duration must be finite and between 1 and 3615 seconds')
    if not 0 <= options.domain <= 232:
        parser.error('--domain must be between 0 and 232')
    if options.worker:
        pattern = rf'/ros_executor_diagnostic_{options.domain}_[0-9]+/worker_[01]'
        if not options.namespace or re.fullmatch(pattern, options.namespace) is None:
            parser.error('--worker requires a namespace generated by this diagnostic')
    elif options.namespace is not None:
        parser.error('--namespace is reserved for child workers')
    return options


def ros_arguments(namespace, *, use_sim_time=False):
    """Keep automatic ROS topics inside the diagnostic namespace as well."""
    root = namespace.rsplit('/', 1)[0]
    result = ['--ros-args', '-r', f'__ns:={namespace}']
    for source, destination in (
        ('/clock', f'{namespace}/clock'),
        ('/rosout', f'{root}/rosout'),
        ('/parameter_events', f'{root}/parameter_events'),
    ):
        result.extend(['-r', f'{source}:={destination}'])
    if use_sim_time:
        result.extend(['-p', 'use_sim_time:=true'])
    return result


def write_event(event, stream=None):
    """Write one flushed JSON record to stdout and optionally an artifact."""
    line = json.dumps(event, sort_keys=True)
    print(line, flush=True)
    if stream is not None:
        stream.write(line + '\n')
        stream.flush()


def run_worker(options):
    """Run only standard subscriptions and parameter services in a child."""
    rclpy.init(args=ros_arguments(options.namespace, use_sim_time=True))
    node = Node('executor_worker')
    node.declare_parameter('diagnostic_worker', True)
    counts = dict.fromkeys(('odometry', 'state', 'clock', 'tf', 'tf_static'), 0)
    lock = threading.Lock()

    def count_callback(name):
        def callback(_message):
            with lock:
                counts[name] += 1
        return callback

    latched = QoSProfile(depth=1, durability=DurabilityPolicy.TRANSIENT_LOCAL)
    # Keep our references separate from rclpy.Node's internal entity lists.
    subscriptions = [
        node.create_subscription(Odometry, 'odom', count_callback('odometry'),
                                 qos_profile_sensor_data),
        node.create_subscription(Bool, 'state', count_callback('state'), latched),
        node.create_subscription(Clock, 'clock', count_callback('clock'), 10),
        node.create_subscription(TFMessage, 'tf', count_callback('tf'), 100),
        node.create_subscription(TFMessage, 'tf_static', count_callback('tf_static'), latched),
    ]
    executor = MultiThreadedExecutor(num_threads=4)
    executor.add_node(node)
    started = time.monotonic()
    next_report = started + 15.0
    write_event({'event': 'worker_ready', 'pid': os.getpid(),
                 'namespace': options.namespace, 'subscriptions': len(subscriptions)})
    try:
        while time.monotonic() - started < options.duration:
            executor.spin_once(timeout_sec=0.1)
            now = time.monotonic()
            if now >= next_report:
                with lock:
                    received = dict(counts)
                write_event({'event': 'worker_progress', 'elapsed_s': now - started,
                             'received': received})
                next_report = now + 15.0
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        executor.shutdown(timeout_sec=3.0)
        # This Jazzy rclpy version does not drain its thread pool in shutdown().
        executor._executor.shutdown(wait=True)
        with lock:
            received = dict(counts)
        write_event({'event': 'worker_stopped', 'elapsed_s': time.monotonic() - started,
                     'received': received})
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
    return 0


def stop_children(children):
    """Stop only our own children, with a shared grace period before killing."""
    for child in children:
        child['exit_before_cleanup'] = child['process'].poll()
        if child['exit_before_cleanup'] is None:
            child['process'].send_signal(signal.SIGINT)
    deadline = time.monotonic() + 6.0
    for child in children:
        try:
            child['process'].wait(timeout=max(0.01, deadline - time.monotonic()))
        except subprocess.TimeoutExpired:
            child['process'].kill()
            child['process'].wait(timeout=3.0)
        child['log'].close()


def child_summary(child):
    """Describe process state and parameter replies using JSON-safe values."""
    return {
        'pid': child['process'].pid,
        'namespace': child['namespace'],
        'returncode': child['process'].poll(),
        'exit_before_cleanup': child.get('exit_before_cleanup'),
        'parameter_replies': child['replies'],
        'parameter_failures': child['failures'],
        'log': str(child['log_path']),
    }


def run_parent(options):
    """Publish isolated telemetry, probe the workers and retain diagnostics."""
    output = options.output_dir
    if output is None:
        output = Path(tempfile.mkdtemp(prefix='ros_executor_diagnostic_'))
    else:
        output = output.expanduser().resolve()
        output.mkdir(parents=True, exist_ok=True)
        if any(output.iterdir()):
            raise ValueError('--output-dir must be empty to preserve earlier diagnostic logs')
    events = (output / 'events.jsonl').open('w')
    fault_log = (output / 'parent_fault.log').open('w')
    faulthandler.enable(file=fault_log, all_threads=True)
    os.environ['ROS_LOG_DIR'] = str(output / 'ros_logs')
    prefix = f'/ros_executor_diagnostic_{options.domain}_{os.getpid()}'
    started = time.monotonic()
    children = []
    node = None
    error = None
    interrupted = False
    counts = dict.fromkeys(('odometry', 'clock', 'tf', 'state', 'tf_static'), 0)
    write_event({'event': 'started', 'pid': os.getpid(), 'domain': options.domain,
                 'namespace': prefix, 'duration_s': options.duration,
                 'interpreter': sys.executable, 'output_dir': str(output),
                 'rmw_implementation': os.environ.get('RMW_IMPLEMENTATION', 'default')}, events)
    try:
        rclpy.init(args=ros_arguments(f'{prefix}/driver'))
        node = Node('executor_diagnostic_driver')
        latched = QoSProfile(depth=1, durability=DurabilityPolicy.TRANSIENT_LOCAL)
        for index in range(2):
            namespace = f'{prefix}/worker_{index}'
            log_path = output / f'worker_{index}.log'
            log = log_path.open('w')
            command = [sys.executable, str(Path(__file__).resolve()), '--worker',
                       '--namespace', namespace, '--domain', str(options.domain),
                       '--duration', str(min(options.duration + 15.0, 3615.0))]
            process = subprocess.Popen(command, stdout=log, stderr=subprocess.STDOUT,
                                       env=os.environ.copy())
            child = {'process': process, 'namespace': namespace, 'log': log,
                     'log_path': log_path, 'replies': 0, 'failures': 0,
                     'pending': None, 'pending_at': None,
                     'next_query': started + min(5.0, options.duration / 2.0)}
            children.append(child)
            child['odom'] = node.create_publisher(
                Odometry, f'{namespace}/odom', qos_profile_sensor_data)
            child['state'] = node.create_publisher(Bool, f'{namespace}/state', latched)
            child['clock'] = node.create_publisher(Clock, f'{namespace}/clock', 10)
            child['tf'] = node.create_publisher(TFMessage, f'{namespace}/tf', 100)
            child['tf_static'] = node.create_publisher(
                TFMessage, f'{namespace}/tf_static', latched)
            child['parameters'] = node.create_client(
                GetParameters, f'{namespace}/executor_worker/get_parameters')
            write_event({'event': 'child_started', 'pid': process.pid,
                         'namespace': namespace, 'command': command}, events)

        odometry = Odometry()
        odometry.header.frame_id = f'{prefix}/odom'
        odometry.child_frame_id = f'{prefix}/base_link'
        odometry.pose.pose.orientation.w = 1.0
        transform = TransformStamped()
        transform.header.frame_id = odometry.header.frame_id
        transform.child_frame_id = odometry.child_frame_id
        transform.transform.rotation.w = 1.0
        static_transform = TransformStamped()
        static_transform.header.frame_id = f'{prefix}/map'
        static_transform.child_frame_id = odometry.header.frame_id
        static_transform.transform.rotation.w = 1.0
        next_odom = next_clock = next_state = started
        next_report = started + 15.0
        while time.monotonic() - started < options.duration:
            now = time.monotonic()
            seconds, nanos = divmod(int((100.0 + now - started) * 1e9), 10**9)
            if now >= next_clock:
                clock = Clock()
                clock.clock.sec, clock.clock.nanosec = seconds, nanos
                transform.header.stamp = clock.clock
                for child in children:
                    child['clock'].publish(clock)
                    child['tf'].publish(TFMessage(transforms=[transform]))
                counts['clock'] += 1
                counts['tf'] += 1
                next_clock = now + 0.02
            if now >= next_odom:
                odometry.header.stamp.sec = seconds
                odometry.header.stamp.nanosec = nanos
                for child in children:
                    child['odom'].publish(odometry)
                counts['odometry'] += 1
                next_odom = now + 0.01
            if now >= next_state:
                for child in children:
                    child['state'].publish(Bool(data=True))
                    child['tf_static'].publish(TFMessage(transforms=[static_transform]))
                counts['state'] += 1
                counts['tf_static'] += 1
                next_state = now + 1.0
            for child in children:
                if child['process'].poll() is not None:
                    raise RuntimeError(f"Worker {child['process'].pid} exited unexpectedly "
                                       f"with code {child['process'].returncode}")
                if child['pending'] is not None:
                    if child['pending'].done():
                        response = child['pending'].result()
                        valid = len(response.values) == 2 and all(
                            value.type == ParameterType.PARAMETER_BOOL and value.bool_value
                            for value in response.values)
                        child['replies'] += int(valid)
                        child['failures'] += int(not valid)
                        child['pending'] = None
                    elif now - child['pending_at'] > 5.0:
                        raise RuntimeError(f"Worker {child['process'].pid} parameter timeout")
                if (now >= child['next_query'] and child['pending'] is None
                        and child['parameters'].service_is_ready()):
                    child['pending'] = child['parameters'].call_async(
                        GetParameters.Request(names=['use_sim_time', 'diagnostic_worker']))
                    child['pending_at'] = now
                    child['next_query'] = now + 15.0
            if now >= next_report:
                write_event({'event': 'progress', 'elapsed_s': now - started,
                             'published_per_worker': dict(counts),
                             'children': [child_summary(child) for child in children]}, events)
                next_report = now + 15.0
            rclpy.spin_once(node, timeout_sec=0.001)
        if any(child['replies'] == 0 or child['failures'] for child in children):
            raise RuntimeError('One or more workers did not return valid parameter replies')
    except KeyboardInterrupt:
        interrupted = True
    except Exception as exception:
        error = f'{type(exception).__name__}: {exception}'
        traceback.print_exc(file=fault_log)
        fault_log.flush()
    finally:
        stop_children(children)
        if node is not None:
            node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()
        summary = {'event': 'finished', 'elapsed_s': time.monotonic() - started,
                   'domain': options.domain, 'error': error, 'interrupted': interrupted,
                   'published_per_worker': counts,
                   'children': [child_summary(child) for child in children]}
        (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n')
        write_event(summary, events)
        events.close()
        faulthandler.disable()
        fault_log.close()
    return int(error is not None or any(child['process'].returncode != 0 for child in children))


def main():
    """Select the driver or worker after establishing the isolated domain."""
    faulthandler.enable(all_threads=True)
    options = arguments()
    os.environ['ROS_DOMAIN_ID'] = str(options.domain)
    os.environ['ROS_AUTOMATIC_DISCOVERY_RANGE'] = 'LOCALHOST'
    if options.worker:
        return run_worker(options)
    return run_parent(options)


if __name__ == '__main__':
    raise SystemExit(main())
